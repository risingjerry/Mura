#!/bin/sh
# Regenerates Sources/MuraCore/RoughJS.swift from the pinned rough.js release.
set -eu
VERSION=4.6.6
SHA256=6853af8619532f3939b156cd16824d2e14f31e71d3df306ad5558eeafacab194
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
(cd "$tmp" && npm pack "roughjs@$VERSION" -q >/dev/null && tar xzf "roughjs-$VERSION.tgz")
echo "$SHA256  $tmp/package/bundled/rough.js" | shasum -a 256 -c - >/dev/null
{
  echo "// Generated by script/vendor_rough.sh — rough.js $VERSION (MIT, https://github.com/rough-stuff/rough). Do not edit."
  echo "let roughJSSource = ##\"\"\""
  cat "$tmp/package/bundled/rough.js"
  echo
  echo "\"\"\"##"
} > Sources/MuraCore/RoughJS.swift
echo "wrote Sources/MuraCore/RoughJS.swift"
